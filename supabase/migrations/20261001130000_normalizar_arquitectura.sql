create or replace function private.sincronizar_perfil_normalizado()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_codigo text;
begin
  if nullif(btrim(new.carrera), '') is not null then
    v_codigo := private.normalizar_clave(new.carrera);
    insert into public.carreras (codigo, nombre)
    values (v_codigo, btrim(new.carrera))
    on conflict (codigo) do nothing;
    select id into new.carrera_id from public.carreras where codigo = v_codigo;
  else
    new.carrera_id := null;
  end if;
  return new;
end;
$$;

create or replace function private.sincronizar_relaciones_perfil()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.areas_interes (codigo, nombre)
  select private.normalizar_clave(x), min(btrim(x))
  from unnest(coalesce(new.areas_interes, '{}'::text[])) x
  where private.normalizar_clave(x) <> ''
  group by private.normalizar_clave(x)
  on conflict (codigo) do nothing;

  delete from public.perfil_areas_interes where perfil_id = new.id;
  insert into public.perfil_areas_interes (perfil_id, area_id)
  select distinct new.id, a.id
  from unnest(coalesce(new.areas_interes, '{}'::text[])) x
  join public.areas_interes a on a.codigo = private.normalizar_clave(x);

  insert into public.skills (codigo, nombre)
  select private.normalizar_clave(x), min(btrim(x))
  from unnest(coalesce(new.skills, '{}'::text[])) x
  where private.normalizar_clave(x) <> ''
    and not exists (
      select 1 from public.skill_aliases sa
      where sa.alias_normalizado = private.normalizar_busqueda(x)
    )
  group by private.normalizar_clave(x)
  on conflict (codigo) do nothing;

  insert into public.skill_aliases (skill_id, alias_normalizado)
  select s.id, private.normalizar_busqueda(x)
  from unnest(coalesce(new.skills, '{}'::text[])) x
  join public.skills s on s.codigo = private.normalizar_clave(x)
  where private.normalizar_busqueda(x) <> ''
  on conflict (alias_normalizado) do nothing;

  delete from public.perfil_skills where perfil_id = new.id;
  insert into public.perfil_skills (perfil_id, skill_id)
  select distinct new.id, sa.skill_id
  from unnest(coalesce(new.skills, '{}'::text[])) x
  join public.skill_aliases sa on sa.alias_normalizado = private.normalizar_busqueda(x);

  insert into public.idiomas (codigo, nombre)
  select private.normalizar_clave(x), min(btrim(x))
  from unnest(coalesce(new.idiomas, '{}'::text[])) x
  where private.normalizar_clave(x) <> ''
    and not exists (
      select 1 from public.idioma_aliases ia
      where ia.alias_normalizado = private.normalizar_busqueda(x)
    )
  group by private.normalizar_clave(x)
  on conflict (codigo) do nothing;

  insert into public.idioma_aliases (idioma_id, alias_normalizado)
  select i.id, private.normalizar_busqueda(x)
  from unnest(coalesce(new.idiomas, '{}'::text[])) x
  join public.idiomas i on i.codigo = private.normalizar_clave(x)
  where private.normalizar_busqueda(x) <> ''
  on conflict (alias_normalizado) do nothing;

  delete from public.perfil_idiomas where perfil_id = new.id;
  insert into public.perfil_idiomas (perfil_id, idioma_id)
  select distinct new.id, ia.idioma_id
  from unnest(coalesce(new.idiomas, '{}'::text[])) x
  join public.idioma_aliases ia on ia.alias_normalizado = private.normalizar_busqueda(x);

  return null;
end;
$$;

create or replace function private.preparar_oferta_normalizada()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_original text;
  v_nombre text;
  v_codigo text;
begin
  if tg_op = 'UPDATE' then
    new.fecha_actualizacion := now();
  end if;

  if nullif(btrim(new.tipo_contrato), '') is not null then
    v_original := regexp_replace(btrim(new.tipo_contrato), '^:\s*', '');
    v_nombre := case
      when private.normalizar_busqueda(v_original) like 'independiente%' then 'Independiente'
      else v_original
    end;
    v_codigo := private.normalizar_clave(v_nombre);
    insert into public.tipos_contrato (codigo, nombre)
    values (v_codigo, v_nombre)
    on conflict (codigo) do nothing;
    select id into new.tipo_contrato_id from public.tipos_contrato where codigo = v_codigo;
    if v_original <> v_nombre then
      new.tipo_contrato_detalle := v_original;
    end if;
    new.tipo_contrato := v_nombre;
  else
    new.tipo_contrato_id := null;
  end if;

  if nullif(btrim(new.tipo_cargo), '') is not null then
    v_nombre := regexp_replace(btrim(new.tipo_cargo), '^:\s*', '');
    v_codigo := private.normalizar_clave(v_nombre);
    insert into public.tipos_cargo (codigo, nombre)
    values (v_codigo, v_nombre)
    on conflict (codigo) do nothing;
    select id into new.tipo_cargo_id from public.tipos_cargo where codigo = v_codigo;
    new.tipo_cargo := v_nombre;
  else
    new.tipo_cargo_id := null;
  end if;
  return new;
end;
$$;

create or replace function private.sincronizar_relaciones_oferta()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_texto text := private.normalizar_busqueda(coalesce(new.puesto, '') || ' ' || coalesce(new.descripcion, ''));
  v_requisitos text := private.normalizar_busqueda(new.requisitos);
begin
  insert into public.facultades (codigo, nombre)
  select private.normalizar_clave(x), min(btrim(x))
  from regexp_split_to_table(coalesce(new.facultades, ''), '[,;]+') x
  where private.normalizar_clave(x) <> ''
  group by private.normalizar_clave(x)
  on conflict (codigo) do nothing;

  delete from public.oferta_facultades where oferta_id = new.id and fuente <> 'manual';
  insert into public.oferta_facultades (oferta_id, facultad_id, fuente, verificada)
  select distinct new.id, f.id, 'importada', true
  from regexp_split_to_table(coalesce(new.facultades, ''), '[,;]+') x
  join public.facultades f on f.codigo = private.normalizar_clave(x)
  on conflict (oferta_id, facultad_id) do update
  set fuente = excluded.fuente, verificada = excluded.verificada;

  delete from public.oferta_areas_interes where oferta_id = new.id and fuente <> 'manual';
  insert into public.oferta_areas_interes (oferta_id, area_id, fuente, verificada)
  select new.id, a.id, 'inferida', false
  from public.areas_interes a
  where a.activa and private.normalizar_busqueda(a.nombre) <> ''
    and position(' ' || private.normalizar_busqueda(a.nombre) || ' ' in ' ' || v_texto || ' ') > 0
  on conflict (oferta_id, area_id) do nothing;

  delete from public.oferta_skills where oferta_id = new.id and fuente <> 'manual';
  insert into public.oferta_skills (oferta_id, skill_id, requerida, fuente, verificada)
  select distinct new.id, sa.skill_id, true, 'inferida', false
  from public.skill_aliases sa
  where sa.alias_normalizado <> ''
    and position(' ' || sa.alias_normalizado || ' ' in ' ' || v_requisitos || ' ') > 0
  on conflict (oferta_id, skill_id) do nothing;

  delete from public.oferta_idiomas where oferta_id = new.id and fuente <> 'manual';
  insert into public.oferta_idiomas (oferta_id, idioma_id, requerido, fuente, verificada)
  select distinct new.id, ia.idioma_id, true, 'inferida', false
  from public.idioma_aliases ia
  where ia.alias_normalizado <> ''
    and position(' ' || ia.alias_normalizado || ' ' in ' ' || v_requisitos || ' ') > 0
  on conflict (oferta_id, idioma_id) do nothing;

  delete from public.oferta_carreras where oferta_id = new.id and fuente <> 'manual';
  insert into public.oferta_carreras (oferta_id, carrera_id, requerida, fuente, verificada)
  select new.id, c.id, false, 'inferida', false
  from public.carreras c
  where c.activa and private.normalizar_busqueda(c.nombre) <> ''
    and position(' ' || private.normalizar_busqueda(c.nombre) || ' ' in ' ' || v_requisitos || ' ') > 0
  on conflict (oferta_id, carrera_id) do nothing;

  delete from public.canales_postulacion where oferta_id = new.id and origen = 'inferido';
  if nullif(btrim(new.enlace), '') is not null then
    insert into public.canales_postulacion (oferta_id, tipo, url, origen, verificado)
    values (new.id, 'portal', btrim(new.enlace), 'inferido', true)
    on conflict do nothing;
  end if;

  insert into public.canales_postulacion (oferta_id, tipo, email, origen, verificado)
  select distinct new.id, 'email', lower(m[1]), 'inferido', false
  from regexp_matches(
    coalesce(new.descripcion, '') || ' ' || coalesce(new.requisitos, ''),
    '([A-Z0-9.!#$%&''*+/=?^_`{|}~-]+@[A-Z0-9](?:[A-Z0-9-]*[A-Z0-9])?(?:\.[A-Z0-9](?:[A-Z0-9-]*[A-Z0-9])?)+)',
    'gi'
  ) m
  on conflict do nothing;

  return null;
end;
$$;

