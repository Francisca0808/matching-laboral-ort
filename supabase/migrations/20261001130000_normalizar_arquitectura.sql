insert into public.documentos_estudiante
  (perfil_id, tipo, bucket_id, object_path, nombre_original, mime_type, es_actual, fecha_carga)
select p.id, 'cv', 'cvs', p.cv_path, 'cv.pdf', 'application/pdf', true,
       coalesce(o.created_at, p.fecha_actualizacion)
from public.perfiles_estudiantes p
left join storage.objects o on o.bucket_id = 'cvs' and o.name = p.cv_path
where nullif(btrim(p.cv_path), '') is not null
on conflict (perfil_id, tipo, bucket_id, object_path) do nothing;

insert into public.perfiles_estudiantes (user_id)
select distinct i.user_id
from public.interacciones_ofertas i
left join public.perfiles_estudiantes p on p.user_id = i.user_id
where p.user_id is null;

