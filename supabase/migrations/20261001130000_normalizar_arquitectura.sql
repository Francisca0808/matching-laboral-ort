create or replace function private.normalizar_clave(p_value text)
returns text
language sql
immutable
set search_path = ''
as $$
  select trim(both '-' from regexp_replace(
    lower(translate(btrim(coalesce(p_value, '')), 'ÁÉÍÓÚÜÑáéíóúüñ', 'AEIOUUNaeiouun')),
    '[^a-z0-9+#.]+', '-', 'g'
  ));
$$;

create or replace function private.normalizar_busqueda(p_value text)
returns text
language sql
immutable
set search_path = ''
as $$
  select btrim(regexp_replace(
    lower(translate(coalesce(p_value, ''), 'ÁÉÍÓÚÜÑáéíóúüñ', 'AEIOUUNaeiouun')),
    '[^a-z0-9+#.]+', ' ', 'g'
  ));
$$;

revoke all on function private.normalizar_clave(text) from public, anon, authenticated;
revoke all on function private.normalizar_busqueda(text) from public, anon, authenticated;

